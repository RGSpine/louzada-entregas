"use client";

import {
  useEffect,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
  type FormEvent,
} from "react";
import { useTheme } from "@/components/theme/ClinicalThemeProvider";
import { toJpeg, toPng } from "html-to-image";
import {
  RadarChart,
  Radar,
  PolarGrid,
  PolarAngleAxis,
  PolarRadiusAxis,
} from "recharts";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Textarea } from "@/components/ui/textarea";
import { Loader2, Sparkles, Download, FileImage, X } from "lucide-react";
import { useRouter } from "next/navigation";
import { toast } from "sonner";
import { premiumFeatureUpsellPath } from "@/lib/premium-feature-upsell";
import { VisualProgressUPlotMetricPanel } from "@/components/dashboard/VisualProgressUPlotMetricPanel";
import { getClinicalCalmChartColors } from "@/lib/chart-colors";
import { clinicalCalmColors } from "@/design/tokens";

type PatientMetric = {
  id: string;
  patientId: string;
  name: string;
  value: number;
  date: string;
  isAutoGenerated: boolean;
  unit?: string | null;
  reasoning?: string | null;
};

interface VisualProgressProps {
  patientId: string;
  patientName: string;
  // "Compartilhamento gamificado" (WhatsApp) segue regra de plano: STARTER+.
  canShare?: boolean;
  /** STARTER ou PRO — geração a partir de texto (`/api/metrics/generate`). */
  canGenerateFromText?: boolean;
  /** PRO — análise multimodal de ficheiro + gravação em PatientExam. */
  canAnalyzeExamFile?: boolean;
}

function fileToBase64(file: File): Promise<string> {
  return new Promise((resolve, reject) => {
    const r = new FileReader();
    r.onload = () => {
      const s = r.result as string;
      const idx = s.indexOf(",");
      resolve(idx >= 0 ? s.slice(idx + 1) : s);
    };
    r.onerror = () => reject(new Error("Leitura do ficheiro falhou."));
    r.readAsDataURL(file);
  });
}

export function VisualProgress({
  patientId,
  patientName,
  canShare = false,
  canGenerateFromText = false,
  canAnalyzeExamFile = false,
}: VisualProgressProps) {
  const router = useRouter();
  const { resolvedTheme } = useTheme();
  const isDark = resolvedTheme === "dark";
  const chartColors = getClinicalCalmChartColors(isDark);

  const chartsRef = useRef<HTMLDivElement | null>(null);

  const [metrics, setMetrics] = useState<PatientMetric[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [generatingFromText, setGeneratingFromText] = useState(false);
  const [generatingFromFile, setGeneratingFromFile] = useState(false);
  const [frequentMetrics, setFrequentMetrics] = useState<string[]>([]);
  const [smartAnalysisText, setSmartAnalysisText] = useState("");
  const [requestedMetrics, setRequestedMetrics] = useState<string[]>([]);
  const [priorityInput, setPriorityInput] = useState("");
  const fileSkillInputRef = useRef<HTMLInputElement | null>(null);
  const datalistId = `visual-metric-suggestions-${patientId}`;
  const [savingManual, setSavingManual] = useState(false);
  const [exporting, setExporting] = useState<null | "png" | "jpeg">(null);
  const [sharing, setSharing] = useState(false);

  const [metricName, setMetricName] = useState("");
  /** Texto livre no input; aceita decimais e valores acima de 10 (ex.: questionários, força). */
  const [metricValueInput, setMetricValueInput] = useState("");
  const [metricDate, setMetricDate] = useState<string>(() => {
    return new Date().toISOString().split("T")[0];
  });

  const loadMetrics = async () => {
    try {
      setLoading(true);
      const res = await fetch(`/api/patients/${patientId}/metrics`, {
        credentials: "same-origin",
      });
      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Erro ao carregar métricas.");
      }
      setMetrics(data.metrics || []);
    } catch (error) {
      console.error("[VisualProgress] loadMetrics", error);
      toast.error("Erro ao carregar métricas da Evolução Visual.");
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadMetrics();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [patientId]);

  useEffect(() => {
    const loadSuggestions = async () => {
      try {
        const res = await fetch("/api/metrics/suggestions", {
          credentials: "same-origin",
        });
        const data = await res.json();
        if (res.ok && data.success && Array.isArray(data.suggestions)) {
          setFrequentMetrics(data.suggestions);
        }
      } catch {
        /* silencioso */
      }
    };
    loadSuggestions();
  }, [patientId]);

  const addRequestedMetric = (name: string) => {
    const t = name.trim();
    if (!t || requestedMetrics.includes(t)) return;
    setRequestedMetrics((prev) => [...prev, t]);
  };

  const removeRequestedMetric = (name: string) => {
    setRequestedMetrics((prev) => prev.filter((x) => x !== name));
  };

  const handleGenerateFromSkillText = async () => {
    if (!canGenerateFromText) {
      router.push(premiumFeatureUpsellPath("visual-evolution"));
      return;
    }
    const text = smartAnalysisText.trim();
    if (!text) {
      toast.error("Cole ou escreva o texto da evolução para analisar.");
      return;
    }
    setGeneratingFromText(true);
    try {
      const res = await fetch("/api/metrics/generate", {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          patientId,
          inputType: "text",
          data: text,
          requestedMetrics,
          referenceDate: metricDate,
        }),
      });
      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Falha na geração.");
      }
      await loadMetrics();
      toast.success(
        `${data.metrics?.length ?? 0} métrica(s) extraída(s) e gravadas.`
      );
    } catch (e) {
      console.error(e);
      toast.error(e instanceof Error ? e.message : "Erro ao gerar métricas.");
    } finally {
      setGeneratingFromText(false);
    }
  };

  const handleGenerateFromSkillFile = async (file: File) => {
    if (!canAnalyzeExamFile) {
      toast.error("Análise de exame/foto requer plano PREMIUM (Pasta de Exames).");
      return;
    }
    let mime = file.type;
    if (!mime || mime === "application/octet-stream") {
      const n = file.name.toLowerCase();
      if (n.endsWith(".pdf")) mime = "application/pdf";
      else if (n.endsWith(".png")) mime = "image/png";
      else if (n.endsWith(".jpg") || n.endsWith(".jpeg")) mime = "image/jpeg";
      else if (n.endsWith(".webp")) mime = "image/webp";
      else if (n.endsWith(".gif")) mime = "image/gif";
    }
    setGeneratingFromFile(true);
    try {
      const b64 = await fileToBase64(file);
      const res = await fetch("/api/metrics/generate", {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          patientId,
          inputType: "file",
          data: b64,
          mimeType: mime,
          fileName: file.name,
          requestedMetrics,
          referenceDate: metricDate,
        }),
      });
      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Falha na análise do ficheiro.");
      }
      await loadMetrics();
      toast.success(
        `${data.metrics?.length ?? 0} métrica(s) a partir do exame. Ficheiro guardado na pasta.`
      );
    } catch (e) {
      console.error(e);
      toast.error(e instanceof Error ? e.message : "Erro ao analisar ficheiro.");
    } finally {
      setGeneratingFromFile(false);
    }
  };

  const handleAutoGenerate = async () => {
    try {
      setGenerating(true);
      const res = await fetch(`/api/patients/${patientId}/metrics/auto-generate`, {
        method: "POST",
        credentials: "same-origin",
      });
      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Erro ao gerar métricas automáticas.");
      }
      setMetrics(data.metrics || []);
      toast.success("Métricas automáticas geradas com sucesso!");
    } catch (error) {
      console.error("[VisualProgress] auto-generate", error);
      toast.error(
        "Não foi possível gerar métricas automáticas. Tente novamente ou ajuste as evoluções."
      );
    } finally {
      setGenerating(false);
    }
  };

  const handleCreateManualMetric = async (e: FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    const raw = metricValueInput.trim().replace(",", ".");
    const value = Number(raw);
    if (!metricName.trim() || raw === "" || !Number.isFinite(value)) {
      toast.error("Preencha o nome da métrica e um valor numérico válido.");
      return;
    }

    try {
      setSavingManual(true);
      const res = await fetch(`/api/patients/${patientId}/metrics`, {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: metricName.trim(),
          value,
          date: metricDate,
          isAutoGenerated: false,
        }),
      });

      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Erro ao salvar métrica.");
      }

      setMetrics((prev) => [...prev, data.metric]);
      setMetricValueInput("");
      toast.success("Métrica adicionada na Evolução Visual.");
    } catch (error) {
      console.error("[VisualProgress] create manual", error);
      toast.error("Erro ao salvar métrica manual.");
    } finally {
      setSavingManual(false);
    }
  };

  const handleDeleteMetric = async (metricId: string) => {
    try {
      const res = await fetch(
        `/api/patients/${patientId}/metrics?id=${encodeURIComponent(metricId)}`,
        {
          method: "DELETE",
          credentials: "same-origin",
        }
      );

      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Erro ao deletar métrica.");
      }

      setMetrics((prev) => prev.filter((m) => m.id !== metricId));
      toast.success("Métrica removida.");
    } catch (error) {
      console.error("[VisualProgress] delete metric", error);
      toast.error("Erro ao deletar métrica.");
    }
  };

  const exportChartsDataUrl = async (format: "png" | "jpeg") => {
    if (!chartsRef.current) {
      throw new Error("Área de gráficos não encontrada para exportar.");
    }

    const backgroundColor = isDark
      ? clinicalCalmColors.dark.card
      : clinicalCalmColors.light.card;
    const element = chartsRef.current;

    if (format === "png") {
      return await toPng(element, {
        cacheBust: true,
        backgroundColor,
      });
    }

    return await toJpeg(element, {
      cacheBust: true,
      quality: 0.92,
      backgroundColor,
    });
  };

  const handleDownloadCharts = async (format: "png" | "jpeg") => {
    try {
      setExporting(format);
      const dataUrl = await exportChartsDataUrl(format);
      const ext = format === "jpeg" ? "jpg" : "png";
      const safeName = patientName
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/(^-|-$)/g, "");
      const fileName = `evolucao-visual-${safeName}-${Date.now()}.${ext}`;

      const link = document.createElement("a");
      link.href = dataUrl;
      link.download = fileName;
      link.click();
      toast.success("Imagem exportada com sucesso!");
    } catch (error) {
      console.error("[VisualProgress] export download", error);
      toast.error("Falha ao exportar a imagem.");
    } finally {
      setExporting(null);
    }
  };

  const handleShareWhatsApp = async () => {
    if (!canShare) {
      router.push(premiumFeatureUpsellPath("visual-evolution"));
      return;
    }
    try {
      setSharing(true);
      const dataUrl = await exportChartsDataUrl("png");

      const res = await fetch(`/api/patients/${patientId}/metrics/share`, {
        method: "POST",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ imageDataUrl: dataUrl, format: "png" }),
      });

      const json = await res.json();
      if (!res.ok || !json.success) {
        throw new Error(json.error || "Erro ao preparar imagem para WhatsApp.");
      }

      const shareText = `Evolução Visual - ${patientName}\n${json.url}`;
      window.open(
        `https://wa.me/?text=${encodeURIComponent(shareText)}`,
        "_blank",
        "noopener,noreferrer"
      );
    } catch (error) {
      console.error("[VisualProgress] share WhatsApp", error);
      toast.error("Não foi possível compartilhar no WhatsApp.");
    } finally {
      setSharing(false);
    }
  };

  /**
   * Séries temporais por nome de métrica — cada uma terá gráfico e eixo Y próprios (uPlot).
   * Datas duplicadas no mesmo segundo: mantém o último ponto.
   */
  const perMetricSeries = useMemo(() => {
    const map = new Map<string, { x: number; y: number }[]>();
    for (const m of metrics) {
      const iso =
        m.date.includes("T") || m.date.length > 12
          ? m.date
          : `${m.date.split("T")[0]}T12:00:00`;
      const x = Date.parse(iso) / 1000;
      if (!Number.isFinite(x)) continue;
      if (!map.has(m.name)) map.set(m.name, []);
      map.get(m.name)!.push({ x, y: m.value });
    }
    Array.from(map.keys()).forEach((name) => {
      const arr = map.get(name)!;
      arr.sort((a, b) => a.x - b.x || a.y - b.y);
      const dedup: typeof arr = [];
      arr.forEach((p) => {
        if (dedup.length && dedup[dedup.length - 1]!.x === p.x) {
          dedup[dedup.length - 1] = p;
        } else {
          dedup.push(p);
        }
      });
      map.set(name, dedup);
    });
    return map;
  }, [metrics]);

  const sortedMetricNames = useMemo(
    () =>
      Array.from(perMetricSeries.keys()).sort((a, b) =>
        a.localeCompare(b, "pt-BR")
      ),
    [perMetricSeries]
  );

  const radarData = useMemo(() => {
    if (metrics.length === 0) return [];

    const latestDate = metrics
      .map((m) => m.date.split("T")[0])
      .sort()
      .pop();

    if (!latestDate) return [];

    const latestMetrics = metrics.filter(
      (m) => m.date.split("T")[0] === latestDate
    );

    return latestMetrics.map((m) => ({
      subject: m.name,
      value: m.value,
    }));
  }, [metrics]);

  const radarRadiusMax = useMemo(() => {
    if (radarData.length === 0) return 10;
    const maxVal = Math.max(
      ...radarData.map((d) => d.value),
      0
    );
    if (maxVal <= 0) return 1;
    return Math.ceil(maxVal * 1.15 * 1000) / 1000;
  }, [radarData]);

  const radarWrapRef = useRef<HTMLDivElement>(null);
  const [radarChartW, setRadarChartW] = useState(0);

  useLayoutEffect(() => {
    if (radarData.length === 0) {
      setRadarChartW(0);
      return;
    }
    const el = radarWrapRef.current;
    if (!el) return;
    const apply = (w: number) => {
      const safe = Math.max(280, Math.floor(w));
      setRadarChartW(safe);
    };
    apply(el.getBoundingClientRect().width);
    const ro = new ResizeObserver((entries) => {
      const cr = entries[0]?.contentRect;
      apply(cr?.width ?? 0);
    });
    ro.observe(el);
    return () => ro.disconnect();
  }, [radarData.length, patientId]);

  const hasData = metrics.length > 0;

  return (
    <Card className="bg-card border-border mb-8">
      <CardHeader className="flex flex-col gap-3 md:flex-row md:items-center md:justify-between">
        <div>
          <CardTitle className="text-foreground flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-success" />
            Evolução Visual
          </CardTitle>
          <p className="text-sm text-muted-foreground mt-1">
            Acompanhe a jornada de {patientName} com as métricas numéricas que você definir (EVA, questionários, força, etc.).
          </p>
        </div>

        <Button
          onClick={handleAutoGenerate}
          disabled={
            generating || generatingFromText || generatingFromFile
          }
          className="bg-success hover:bg-success/90 gap-2"
        >
          {generating ? (
            <>
              <Loader2 className="h-4 w-4 animate-spin" />
              Gerando com IA...
            </>
          ) : (
            <>
              <Sparkles className="h-4 w-4" />
              Atualizar com IA
            </>
          )}
        </Button>
      </CardHeader>

      <CardContent className="space-y-8">
        {/* Pipeline Analysis / Structured output – Evolução Visual */}
        <div className="rounded-lg border border-success/30 bg-success/10 dark:bg-success/15 p-4 space-y-4">
          <div>
            <p className="text-xs font-semibold text-success">
              Extração estruturada (IA)
            </p>
            <p className="text-[11px] text-muted-foreground mt-0.5">
              Texto clínico (Profissional+) ou exame em ficheiro (Premium). Opcional: métricas prioritárias para orientar o modelo.
            </p>
          </div>

          <div className="space-y-2">
            <label className="block text-xs font-medium text-muted-foreground">
              Texto para análise (evolução, notas clínicas…)
            </label>
            <Textarea
              value={smartAnalysisText}
              onChange={(e) => setSmartAnalysisText(e.target.value)}
              placeholder="Cole aqui o texto da evolução ou trecho do prontuário que contém medidas subjetivas ou objetivas…"
              className="min-h-[100px] text-sm bg-muted dark:bg-card border-border dark:border-border"
              disabled={!canGenerateFromText}
            />
          </div>

          <div className="space-y-2">
            <span className="block text-xs font-medium text-muted-foreground">
              Métricas prioritárias (opcional)
            </span>
            <div className="flex flex-wrap gap-2">
              {requestedMetrics.map((r) => (
                <button
                  key={r}
                  type="button"
                  onClick={() => removeRequestedMetric(r)}
                  className="inline-flex items-center gap-1 rounded-full bg-success/15 text-success px-2.5 py-0.5 text-xs border border-success/30"
                >
                  {r}
                  <X className="h-3 w-3" />
                </button>
              ))}
            </div>
            <div className="flex flex-wrap gap-2">
              <input
                type="text"
                value={priorityInput}
                onChange={(e) => setPriorityInput(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter") {
                    e.preventDefault();
                    addRequestedMetric(priorityInput);
                    setPriorityInput("");
                  }
                }}
                placeholder="Nome e Enter"
                className="max-w-xs rounded-md border border-border dark:border-border bg-muted dark:bg-card px-2 py-1.5 text-sm"
              />
              <Button
                type="button"
                variant="outline"
                size="sm"
                className="border-success/40 text-success"
                onClick={() => {
                  addRequestedMetric(priorityInput);
                  setPriorityInput("");
                }}
              >
                Adicionar
              </Button>
            </div>
            {frequentMetrics.length > 0 && (
              <div className="flex flex-wrap gap-1.5 pt-1">
                <span className="text-[10px] text-muted-foreground w-full">Sugestões frequentes:</span>
                {frequentMetrics.map((m) => (
                  <button
                    key={m}
                    type="button"
                    onClick={() => {
                      addRequestedMetric(m);
                      setMetricName(m);
                    }}
                    className="text-[11px] rounded-full bg-muted/80 dark:bg-muted px-2 py-0.5 text-foreground/90 hover:bg-success/20"
                  >
                    {m}
                  </button>
                ))}
              </div>
            )}
          </div>

          <div className="flex flex-wrap gap-2">
            <Button
              type="button"
              disabled={generatingFromText || generatingFromFile}
              onClick={handleGenerateFromSkillText}
              className="bg-success hover:bg-success/90 gap-2"
            >
              {generatingFromText ? (
                <Loader2 className="h-4 w-4 animate-spin" />
              ) : (
                <Sparkles className="h-4 w-4" />
              )}
              ✨ Gerar gráfico de evoluções (texto)
            </Button>
            <Button
              type="button"
              disabled={generatingFromText || generatingFromFile}
              onClick={() => {
                if (!canAnalyzeExamFile) {
                  router.push(premiumFeatureUpsellPath("exam-folder-upload"));
                  return;
                }
                fileSkillInputRef.current?.click();
              }}
              className="bg-muted hover:bg-card dark:bg-muted dark:hover:bg-card dark:text-foreground gap-2"
            >
              {generatingFromFile ? (
                <Loader2 className="h-4 w-4 animate-spin" />
              ) : (
                <FileImage className="h-4 w-4" />
              )}
              📸 Analisar exame/foto para gráfico
            </Button>
            <input
              ref={fileSkillInputRef}
              type="file"
              className="hidden"
              accept=".pdf,image/jpeg,image/png,image/webp,image/gif,application/pdf"
              onChange={(e) => {
                const f = e.target.files?.[0];
                e.target.value = "";
                if (f) void handleGenerateFromSkillFile(f);
              }}
            />
          </div>
          {!canGenerateFromText && (
            <p className="text-[11px] text-success">
              Geração a partir de texto: plano Profissional ou Premium.
            </p>
          )}
          {!canAnalyzeExamFile && (
            <p className="text-[11px] text-success">
              Análise de ficheiro: plano PREMIUM (inclui armazenamento na pasta de exames).
            </p>
          )}
        </div>

        {/* Formulário de métrica manual */}
        <form
          onSubmit={handleCreateManualMetric}
          className="grid grid-cols-1 md:grid-cols-[2fr,1fr,1fr,auto] gap-3 items-end"
        >
          <div>
            <label className="block text-xs font-medium text-muted-foreground mb-1">
              Nome da Métrica
            </label>
            <input
              type="text"
              value={metricName}
              onChange={(e) => setMetricName(e.target.value)}
              list={datalistId}
              className="w-full rounded-md border border-border dark:border-border bg-muted dark:bg-card px-3 py-2 text-sm text-foreground focus:outline-none focus:ring-2 focus:ring-success"
              placeholder="Ex.: Mobilidade, EVA, SF-36, carga (kg)…"
            />
            <datalist id={datalistId}>
              {frequentMetrics.map((m) => (
                <option key={m} value={m} />
              ))}
            </datalist>
            {frequentMetrics.length > 0 && (
              <div className="flex flex-wrap gap-1 mt-1.5">
                {frequentMetrics.map((m) => (
                  <button
                    key={`pill-${m}`}
                    type="button"
                    onClick={() => setMetricName(m)}
                    className="text-[10px] rounded-md bg-muted/70 dark:bg-muted px-1.5 py-0.5 text-muted-foreground"
                  >
                    {m}
                  </button>
                ))}
              </div>
            )}
          </div>

          <div>
            <label className="block text-xs font-medium text-muted-foreground mb-1">
              Valor
            </label>
            <input
              type="text"
              inputMode="decimal"
              value={metricValueInput}
              onChange={(e) => setMetricValueInput(e.target.value)}
              placeholder="Ex.: 3, 12,5, 80"
              className="w-full rounded-md border border-border dark:border-border bg-muted dark:bg-card px-3 py-2 text-sm text-foreground focus:outline-none focus:ring-2 focus:ring-success"
            />
          </div>

          <div>
            <label className="block text-xs font-medium text-muted-foreground mb-1">
              Data
            </label>
            <input
              type="date"
              value={metricDate}
              onChange={(e) => setMetricDate(e.target.value)}
              className="w-full rounded-md border border-border dark:border-border bg-muted dark:bg-card px-3 py-2 text-sm text-foreground focus:outline-none focus:ring-2 focus:ring-success"
            />
          </div>

          <Button
            type="submit"
            disabled={savingManual}
            className="bg-primary hover:bg-primary/90 whitespace-nowrap"
          >
            {savingManual ? (
              <>
                <Loader2 className="h-4 w-4 animate-spin mr-2" />
                Salvando...
              </>
            ) : (
              "Adicionar ponto"
            )}
          </Button>
        </form>

        {loading && !hasData && (
          <div className="flex items-center justify-center py-10">
            <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
          </div>
        )}

        {!loading && !hasData && (
          <p className="text-sm text-muted-foreground">
            Ainda não há métricas registradas. Gere automaticamente com IA ou adicione pontos manualmente.
          </p>
        )}

        {hasData && (
          <>
            {/* Exportação e compartilhamento */}
            <div className="flex flex-wrap items-center gap-2">
              <Button
                type="button"
                onClick={() => handleDownloadCharts("png")}
                disabled={exporting !== null || sharing}
                className="bg-card hover:bg-muted dark:bg-muted dark:hover:bg-card dark:text-foreground gap-2"
              >
                <Download className="h-4 w-4" />
                {exporting === "png" ? "Exportando..." : "Baixar PNG"}
              </Button>
              <Button
                type="button"
                onClick={() => handleDownloadCharts("jpeg")}
                disabled={exporting !== null || sharing}
                className="bg-muted hover:bg-muted text-foreground dark:bg-muted dark:hover:bg-muted dark:text-foreground gap-2 border border-border dark:border-border"
              >
                <Download className="h-4 w-4" />
                {exporting === "jpeg" ? "Exportando..." : "Baixar JPEG"}
              </Button>
              <Button
                type="button"
                onClick={handleShareWhatsApp}
                disabled={exporting !== null || sharing}
                className="bg-primary hover:bg-primary/90 gap-2"
              >
                {sharing ? (
                  <>
                    <Loader2 className="h-4 w-4 animate-spin" />
                    Preparando...
                  </>
                ) : (
                  "Compartilhar no WhatsApp"
                )}
              </Button>
            </div>

            {/* Gráficos (alvo da exportação) */}
            <div ref={chartsRef} className="grid grid-cols-1 lg:grid-cols-2 gap-6">
              {/* Séries temporais: uma linha por métrica, eixo Y independente (uPlot). */}
              <div className="space-y-3 min-w-0">
                <div>
                  <p className="text-xs uppercase tracking-wide text-muted-foreground mb-1">
                    Evolução no tempo
                  </p>
                  <p className="text-[11px] text-muted-foreground dark:text-muted-foreground leading-snug">
                    Cada métrica tem escala própria no eixo Y. Renderização com uPlot (MIT,
                    canvas, foco em séries temporais).
                  </p>
                </div>
                <div className="space-y-4 max-h-[min(70vh,720px)] overflow-y-auto pr-1">
                  {sortedMetricNames.map((name, idx) => (
                    <VisualProgressUPlotMetricPanel
                      key={name}
                      title={name}
                      points={perMetricSeries.get(name)!}
                      stroke={chartColors.series[idx % chartColors.series.length]!}
                      isDark={isDark}
                    />
                  ))}
                </div>
              </div>

              {/* Gráfico radar: fotografia atual */}
              <div
                ref={radarWrapRef}
                className="h-72 w-full min-h-[288px] min-w-0"
              >
                <p className="text-xs uppercase tracking-wide text-muted-foreground mb-2">
                  Fotografia atual (última data registrada)
                </p>
                {radarData.length === 0 ? (
                  <p className="text-sm text-muted-foreground">
                    Gere ao menos uma métrica para visualizar o radar.
                  </p>
                ) : radarChartW > 0 ? (
                  <RadarChart
                    width={radarChartW}
                    height={288}
                    data={radarData}
                  >
                    <PolarGrid stroke={`${chartColors.grid}55`} />
                    <PolarAngleAxis
                      dataKey="subject"
                      tick={{ fill: chartColors.yTickFill, fontSize: 11 }}
                    />
                    <PolarRadiusAxis
                      angle={30}
                      domain={[0, radarRadiusMax]}
                      tick={{ fill: chartColors.tickFill, fontSize: 10 }}
                    />
                    <Radar
                      name={patientName}
                      dataKey="value"
                      stroke={chartColors.primary}
                      fill={chartColors.primary}
                      fillOpacity={0.4}
                    />
                  </RadarChart>
                ) : (
                  <div
                    className="h-[288px] w-full animate-pulse rounded-md bg-muted/50 dark:bg-muted/40"
                    aria-hidden
                  />
                )}
              </div>
            </div>
          </>
        )}

        {/* Lista compacta das métricas registradas */}
        {hasData && (
          <div className="border-t border-border dark:border-border pt-4 mt-2 space-y-2">
            <p className="text-xs uppercase tracking-wide text-muted-foreground">
              Pontos registrados
            </p>
            <div className="max-h-40 overflow-y-auto space-y-1 text-xs">
              {metrics
                .slice()
                .sort(
                  (a, b) =>
                    a.date.localeCompare(b.date) || a.name.localeCompare(b.name)
                )
                .map((m) => (
                  <div
                    key={m.id}
                    className="flex items-center justify-between rounded-md bg-muted dark:bg-card/60 px-2 py-1"
                  >
                    <span className="text-muted-foreground">
                      {m.date.split("T")[0]} · {m.name} ·{" "}
                      <span className="font-semibold">
                        {new Intl.NumberFormat("pt-BR", {
                          maximumFractionDigits: 4,
                        }).format(m.value)}
                        {m.unit ? (
                          <span className="font-normal text-muted-foreground">
                            {" "}
                            ({m.unit})
                          </span>
                        ) : null}
                      </span>
                      {m.isAutoGenerated && (
                        <span className="ml-1 text-[10px] uppercase text-success">
                          (IA)
                        </span>
                      )}
                    </span>
                    <button
                      type="button"
                      onClick={() => handleDeleteMetric(m.id)}
                      className="text-[11px] text-muted-foreground hover:text-destructive"
                    >
                      remover
                    </button>
                  </div>
                ))}
            </div>
          </div>
        )}
      </CardContent>
    </Card>
  );
}

