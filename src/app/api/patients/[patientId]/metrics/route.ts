import { NextRequest, NextResponse } from "next/server";
import { createSupabaseServerClient } from "@/lib/supabase-server";
import { prisma } from "@/lib/prisma";
import { PatientMetricCreateSchema, RoutePatientIdSchema } from "@/lib/api-schemas";

async function ensurePatientOwnership(patientId: string) {
  const supabase = await createSupabaseServerClient();
  const {
    data: { user: authUser },
    error: authError,
  } = await supabase.auth.getUser();

  if (authError || !authUser?.email) {
    return { error: "Não autenticado. Faça login para continuar.", status: 401 as const };
  }

  const dbUser = await prisma.user.findFirst({
    where: {
      OR: [{ authUserId: authUser.id }, { email: authUser.email ?? "" }],
    },
    select: { id: true },
  });

  if (!dbUser) {
    return { error: "Usuário não encontrado.", status: 404 as const };
  }

  const patient = await prisma.patient.findFirst({
    where: { id: patientId, userId: dbUser.id },
    select: { id: true },
  });

  if (!patient) {
    return { error: "Paciente não encontrado ou não pertence a você.", status: 404 as const };
  }

  return { success: true as const };
}

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ patientId: string }> }
) {
  try {
    const { patientId } = await params;
    const ownership = await ensurePatientOwnership(patientId);
    if ("error" in ownership) {
      return NextResponse.json({ success: false, error: ownership.error }, { status: ownership.status });
    }

    const metrics = await prisma.patientMetric.findMany({
      where: { patientId },
      orderBy: { date: "asc" },
    });

    return NextResponse.json({ success: true, metrics });
  } catch (error) {
    console.error("[GET metrics] Erro:", error);
    return NextResponse.json(
      { success: false, error: "Erro ao buscar métricas do paciente." },
      { status: 500 }
    );
  }
}

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ patientId: string }> }
) {
  try {
    const { patientId: rawPatientId } = await params;
    const paramsParsed = RoutePatientIdSchema.safeParse({ patientId: rawPatientId });
    if (!paramsParsed.success) {
      return NextResponse.json({ success: false, error: "ID de paciente inválido." }, { status: 400 });
    }
    const { patientId } = paramsParsed.data;

    const ownership = await ensurePatientOwnership(patientId);
    if ("error" in ownership) {
      return NextResponse.json({ success: false, error: ownership.error }, { status: ownership.status });
    }

    const rawBody = await request.json().catch(() => null);
    const parsed = PatientMetricCreateSchema.safeParse(rawBody);
    if (!parsed.success) {
      return NextResponse.json(
        { success: false, error: "Dados inválidos.", issues: parsed.error.flatten() },
        { status: 400 },
      );
    }
    const body = parsed.data;

    const metric = await prisma.patientMetric.create({
      data: {
        patientId,
        name: body.name,
        value: body.value,
        date: new Date(body.date),
        isAutoGenerated: body.isAutoGenerated ?? false,
      },
    });

    return NextResponse.json({ success: true, metric });
  } catch (error) {
    console.error("[POST metrics] Erro:", error);
    return NextResponse.json(
      { success: false, error: "Erro ao criar métrica para o paciente." },
      { status: 500 }
    );
  }
}

export async function DELETE(
  request: NextRequest,
  { params }: { params: Promise<{ patientId: string }> }
) {
  try {
    const { patientId } = await params;
    const ownership = await ensurePatientOwnership(patientId);
    if ("error" in ownership) {
      return NextResponse.json({ success: false, error: ownership.error }, { status: ownership.status });
    }

    const { searchParams } = new URL(request.url);
    const metricId = searchParams.get("id");

    if (!metricId) {
      return NextResponse.json(
        { success: false, error: "Parâmetro 'id' da métrica é obrigatório." },
        { status: 400 }
      );
    }

    const existing = await prisma.patientMetric.findFirst({
      where: { id: metricId, patientId },
      select: { id: true },
    });

    if (!existing) {
      return NextResponse.json(
        { success: false, error: "Métrica não encontrada para este paciente." },
        { status: 404 }
      );
    }

    await prisma.patientMetric.delete({ where: { id: metricId } });

    return NextResponse.json({ success: true });
  } catch (error) {
    console.error("[DELETE metrics] Erro:", error);
    return NextResponse.json(
      { success: false, error: "Erro ao deletar métrica do paciente." },
      { status: 500 }
    );
  }
}

