import { NextRequest, NextResponse } from "next/server";
import { createSupabaseServerClient } from "@/lib/supabase-server";
import { prisma } from "@/lib/prisma";
import { extractVisualMetricsForPatient } from "@/app/actions/ai";
import { RoutePatientIdSchema } from "@/lib/api-schemas";
import {
  aiBillingRateLimitMessage,
  enforceAiBillingRateLimit,
} from "@/lib/ai-billing-rate-limit";
import { getRequestClientIp } from "@/lib/request-client-ip";

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ patientId: string }> }
) {
  try {
    const { patientId: rawPatientId } = await params;
    const paramsParsed = RoutePatientIdSchema.safeParse({ patientId: rawPatientId });
    if (!paramsParsed.success) {
      return NextResponse.json({ error: "ID de paciente inválido." }, { status: 400 });
    }
    const { patientId } = paramsParsed.data;

    const supabase = await createSupabaseServerClient();
    const {
      data: { user: authUser },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !authUser?.email) {
      return NextResponse.json(
        { error: "Não autenticado. Faça login para continuar." },
        { status: 401 }
      );
    }

    // Garantir que o paciente pertence ao usuário logado
    const dbUser = await prisma.user.findFirst({
      where: {
        OR: [{ authUserId: authUser.id }, { email: authUser.email ?? "" }],
      },
      select: { id: true },
    });

    if (!dbUser) {
      return NextResponse.json(
        { error: "Usuário não encontrado." },
        { status: 404 }
      );
    }

    const rl = await enforceAiBillingRateLimit({
      userKey: (authUser.email ?? authUser.id).toLowerCase(),
      ip: getRequestClientIp(request.headers),
    });
    if (!rl.allowed) {
      return NextResponse.json(
        { error: aiBillingRateLimitMessage(rl.resetIn) },
        { status: 429 },
      );
    }

    const patient = await prisma.patient.findFirst({
      where: { id: patientId, userId: dbUser.id },
      select: { id: true },
    });

    if (!patient) {
      return NextResponse.json(
        { error: "Paciente não encontrado." },
        { status: 404 }
      );
    }

    const metrics = await extractVisualMetricsForPatient(patientId);

    // Apagar métricas automáticas anteriores para evitar duplicação
    await prisma.patientMetric.deleteMany({
      where: { patientId, isAutoGenerated: true },
    });

    if (metrics.length > 0) {
      await prisma.patientMetric.createMany({
        data: metrics.map((m) => ({
          patientId,
          name: m.name,
          value: m.value,
          date: new Date(m.date),
          isAutoGenerated: true,
        })),
      });
    }

    const saved = await prisma.patientMetric.findMany({
      where: { patientId },
      orderBy: { date: "asc" },
    });

    return NextResponse.json({ success: true, metrics: saved });
  } catch (error) {
    console.error("[api/patients/[patientId]/metrics/auto-generate] Erro:", error);
    return NextResponse.json(
      {
        success: false,
        error:
          error instanceof Error
            ? error.message
            : "Erro ao gerar métricas automáticas.",
      },
      { status: 500 }
    );
  }
}

