import { z } from "zod";

/** IDs Prisma (CUID) — evita rejeitar IDs válidos por versão do validador cuid. */
export const prismaIdSchema = z.string().trim().min(8).max(64);

export const AssignPatientSchema = z.object({
  patientId: prismaIdSchema,
  userId: prismaIdSchema,
});

export const PatientMetricCreateSchema = z.object({
  name: z.string().trim().min(1).max(200),
  value: z
    .number()
    .finite()
    .refine((v) => Math.abs(v) <= 1e7, {
      message: "Valor fora do intervalo permitido (|valor| ≤ 10 000 000).",
    }),
  date: z.string().trim().min(8).max(64),
  isAutoGenerated: z.boolean().optional(),
});

export const MetricsShareSchema = z.object({
  imageDataUrl: z.string().min(32).max(12_000_000),
  format: z.enum(["png", "jpeg"]).optional(),
});

export const RoutePatientIdSchema = z.object({
  patientId: prismaIdSchema,
});

export const RouteJobIdSchema = z.object({
  jobId: prismaIdSchema,
});
